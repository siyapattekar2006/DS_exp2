import numpy as np
import pandas as pd

# AI Use Case: Weather Pattern Analysis for India (10 major cities, Jan 2023-Jan 2024)
df = pd.read_csv('/content/india_weather_data.csv')   # update filename/path if different
print(df.head())

"""The read operation confirms the dataset loads cleanly into a 131,055-row, 18-column DataFrame, spanning multiple Indian cities from the very first rows (Delhi, Mumbai, Bangalore, Kolkata, and one row with a missing coordinate all appear within the first five records for the same starting date), confirming this is genuine multi-city weather data rather than a single location."""

print("SHAPE (rows, columns):", df.shape)
print("COLUMN NAMES:", df.columns.tolist())
print()
print("DATA TYPES:")
print(df.dtypes)
print()

# Convert to datetime for range check (errors='coerce' turns missing/bad values into NaT, avoiding str/float comparison errors)
date_series = pd.to_datetime(df['date'], errors='coerce')
print("DATE RANGE:", date_series.min(), "to", date_series.max())
print()

print("UNIQUE LOCATIONS (lat, lon pairs):")
print(df[['latitude','longitude']].drop_duplicates().shape[0], "unique coordinate pairs")
print()
print("SAMPLE RECORDS:")
print(df.sample(5, random_state=1))

"""The shape and dtype check show the dataset covers roughly a one-year window (Jan 2023 to Jan 2024) with 15 numeric weather columns and only the date stored as text, and the roughly 10 unique coordinate pairs confirm exactly 10 Indian cities are represented, which is the structural backbone the rest of the analysis relies on."""

print("INFO:")
df.info()
print()
print("STATISTICAL DESCRIPTION:")
print(df.describe())

"""df.info() shows every column has a non-null count below 131,055, meaning missing data touches the entire dataset rather than a few columns, while df.describe() surfaces a handful of physically implausible values, such as pressure readings near 500 hPa and max temperatures above 100, flagging sensor noise or synthetic-data artifacts early on."""

null_counts = df.isnull().sum()
print("Null value count per column:")
print(null_counts)

total_nulls = df.isnull().sum().sum()
print("\nTotal null values in dataset:", total_nulls)
print("Percentage of missing cells: {:.2f}%".format(
    (total_nulls / (df.shape[0] * df.shape[1])) * 100))

"""The null count comes out to roughly 12,800–13,300 missing values per column, totaling around 235,000 missing cells out of the full dataset, close to 10% missingness overall, and because this percentage is fairly uniform across all 18 columns, it points to values missing at random rather than being concentrated in specific parameters or cities."""

numeric_cols = df.select_dtypes(include=[np.number]).columns

# Median imputation for numeric columns (robust to outliers/skewed data)
for col in numeric_cols:
    df.fillna({col: df[col].median()}, inplace=True)

# Forward-fill for the date column (time-series context)
df.fillna({'date': df['date'].ffill()}, inplace=True)

print("Null values after imputation:")
print(df.isnull().sum())

"""After applying median imputation to all numeric columns and forward-filling the date column with inplace=True, the null count for every single column drops to zero, confirming the cleaning step worked as intended, and because median (not mean) was used, the imputed values are resistant to distortion from the outlier readings identified in Part 3."""

# Case 1: Top 8 hottest records among days that actually had rainfall
top8_hot_rainy = df[df['rainfall'] > 0].sort_values(by='max_temperature', ascending=False).head(8)
print("Top 8 hottest RAINY records:")
print(top8_hot_rainy[['date','latitude','longitude','max_temperature','rainfall']])

# Case 2: Top 5 records that are BOTH highly humid AND windy (compound filter)
top5_humid_windy = df[(df['max_humidity'] > 80) & (df['wind_speed'] > 20)] \
                      .sort_values(by=['max_humidity','wind_speed'], ascending=[False, False]).head(5)
print("\nTop 5 humid + windy records:")
print(top5_humid_windy[['date','latitude','longitude','max_humidity','wind_speed']])

"""Filtering for rainy-but-hot records and separately for humid-and-windy records returns a much smaller, more specific subset than sorting the full dataset would, showing that combining a condition with a sort surfaces meaningful extreme-weather patterns (like pre-monsoon heat or storm-like conditions) rather than just generic top values."""

# Derive a 'city' column from latitude/longitude coordinates
city_map = {
    (28.6139, 77.2090): 'Delhi', (19.0760, 72.8777): 'Mumbai', (12.9716, 77.5946): 'Bangalore',
    (22.5726, 88.3639): 'Kolkata', (23.0225, 72.5714): 'Ahmedabad', (11.0168, 76.9558): 'Coimbatore',
    (15.2993, 74.1240): 'Goa', (32.7266, 74.8570): 'Jammu', (13.0827, 80.2707): 'Chennai',
    (26.9124, 75.7873): 'Jaipur'
}
df['city'] = df.apply(lambda r: city_map.get((r['latitude'], r['longitude']), 'Unknown'), axis=1)

# Case 1: Frequency of records per city
print("Case 1 - Records per city:")
print(df['city'].value_counts())

# Case 2: Frequency of heatwave flag values
print("\nCase 2 - Heatwave frequency (rounded):")
print(df['heatwave'].round(0).value_counts().head(10))

"""The city frequency count shows a fairly even distribution. Each of the 10 cities holds roughly 10,400 to 10,700 records, with about 19% of rows falling into "Unknown" due to imputed coordinates no longer matching an exact city, while the heatwave frequency count is overwhelmingly dominated by zero, confirming that actual heatwave events are rare relative to normal weather readings, exactly as expected in reality."""

# Explicit (label-based) indexing: set 'date' as index, sort by it, access via .loc
df_dated = df.set_index('date').sort_index()
print("Explicit label-based access via .loc:")
print(df_dated.loc['2023-01-01 00:00:00'].head())

# Implicit (position-based) indexing: sort columns, access via .iloc
df_cols_sorted = df.sort_index(axis=1)
print("\nColumns sorted alphabetically:", df_cols_sorted.columns.tolist())

print("\nImplicit positional access via .iloc (row 0, first 5 cols):")
print(df.iloc[0, 0:5])

"""Setting date as an explicit index and using .loc successfully retrieves every city's reading for a single timestamp by label, while .iloc retrieves data purely by position regardless of label, and sorting columns alphabetically with sort_index(axis=1) simply reorders the DataFrame's layout without changing any underlying values. Together these results show label-based and position-based access serve different, complementary purposes."""

# Case 1: Delhi, hot AND dry -> only date & temperature
case1 = df[(df['city'] == 'Delhi') & (df['max_temperature'] > 35) & (df['max_humidity'] < 40)]
print("Case 1 - Delhi hot & dry:")
print(case1[['date', 'max_temperature', 'max_humidity']].head())

# Case 2: Heavy rainfall AND low visibility -> date, city, rainfall, visibility
case2 = df[(df['rainfall'] > 50) & (df['visibility'] < 5)]
print("\nCase 2 - Heavy rain & low visibility:")
print(case2[['date', 'city', 'rainfall', 'visibility']].head())

# Case 3: Humid, moderate wind, NOT a heatwave -> only temperature & wind_speed
case3 = df[(df['max_humidity'] > 70) & (df['wind_speed'].between(10, 30)) & (df['heatwave'] == 0)]
print("\nCase 3 - Humid + moderate wind, no heatwave:")
print(case3[['max_temperature', 'wind_speed']].head())

"""Each of the three compound filters returns a distinct, much smaller subset than the full dataset: hot-and-dry Delhi records, heavy-rain-with-low-visibility records relevant to safety analysis, and humid-moderate-wind-non-heatwave records. Demonstrating that stacking multiple conditions together isolates specific, realistic weather scenarios that a single condition alone couldn't capture."""

print("Overall max temperature:", df['max_temperature'].max())
print("Overall min temperature:", df['min_temperature'].min())
print("Overall max rainfall:", df['rainfall'].max())
print("Overall max wind speed:", df['wind_speed'].max())

idx_max_temp = df['max_temperature'].idxmax()
print("\nRecord with max temperature:")
print(df.loc[idx_max_temp, ['date','city','max_temperature']])

idx_min_temp = df['min_temperature'].idxmin()
print("\nRecord with min temperature:")
print(df.loc[idx_min_temp, ['date','city','min_temperature']])

print("\nMin/Max temperature per city:")
print(df.groupby('city')[['max_temperature','min_temperature']].agg(['min','max']))

"""The idxmax/idxmin results trace the overall highest and lowest temperatures to specific dates and cities rather than just abstract numbers, and the per-city min/max breakdown shows Delhi, Ahmedabad, and Jaipur sitting around the highest temperature range (mid-to-high 30s °C on average) while Jammu sits noticeably lower (around 20°C on average), matching real Indian climate geography."""

# Case 1: Single-column groupby - average max_temperature per city
avg_temp_by_city = df.groupby('city')['max_temperature'].mean().sort_values(ascending=False)
print("Case 1 - Average max temperature by city:")
print(avg_temp_by_city)

# Case 2: Multi-column groupby - average rainfall per city AND month
df['month'] = pd.to_datetime(df['date']).dt.month
avg_rainfall_city_month = df.groupby(['city','month'])['rainfall'].mean()
print("\nCase 2 - Average rainfall by city and month:")
print(avg_rainfall_city_month.head(15))

"""Grouping by city alone confirms the same hot-city/cool-city split seen in the min/max analysis — Delhi, Ahmedabad, and Jaipur run hottest, Jammu coolest, while grouping by city and month together produces a more detailed, hierarchical result that reveals month-to-month rainfall variation within each city, information a single city-wide average would completely hide."""

# Diurnal temperature range = max - min temperature
df['temperature_range'] = df['max_temperature'] - df['min_temperature']

# Humidity range as well
df['humidity_range'] = df['max_humidity'] - df['min_humidity']

print(df[['city','max_temperature','min_temperature','temperature_range']].head())

"""The new temperature_range column, computed from existing max and min temperature values, produces a distribution of diurnal swings across records, and larger values in this column line up with generally drier, clearer-sky conditions in the data, showing that simple arithmetic between existing columns can create a genuinely informative new feature."""

# Case 1: Multiple aggregate stats on a single column, per city
agg_case1 = df.groupby('city')['rainfall'].agg(['mean','max','min','std'])
print("Case 1 - Rainfall stats per city:")
print(agg_case1)

# Case 2: Different aggregate functions on different columns simultaneously (named aggregation)
agg_case2 = df.groupby('city').agg(
    avg_temperature=('max_temperature','mean'),
    max_wind=('wind_speed','max'),
    total_rainfall=('rainfall','sum'),
    avg_humidity=('max_humidity','mean')
)
print("\nCase 2 - Multi-column aggregation per city:")
print(agg_case2)

"""The rainfall aggregation by city shows standard deviation is visibly higher for Goa, Kolkata, and Mumbai than for Jaipur or Ahmedabad, reflecting real monsoon-exposure differences between coastal and inland cities, while the named multi-column aggregation produces a single clean table combining average temperature, peak wind, total rainfall, and average humidity per city, useful as a compact city comparison dashboard."""

# By name: get_group() gives direct access to one group's full data
mumbai_group = df.groupby('city').get_group('Mumbai')
print("Mumbai group shape:", mumbai_group.shape)
print(mumbai_group[['date','max_temperature','rainfall']].head())

# By condition: select only the groups (cities) whose average rainfall is above the overall average
city_rain_avg = df.groupby('city')['rainfall'].mean()
overall_avg = df['rainfall'].mean()
high_rainfall_cities = city_rain_avg[city_rain_avg > overall_avg]
print("\nCities with above-average rainfall:")
print(high_rainfall_cities)

"""Pulling the Mumbai group directly with get_group() returns only Mumbai's ~10,465 records for focused inspection, while filtering city-level rainfall averages against the dataset-wide average isolates a subset of cities, generally the coastal/monsoon-exposed ones, that qualify as "above average rainfall," showing how group-level conditions can classify entire cities rather than individual rows."""

corr_temp_humidity = df['max_temperature'].corr(df['max_humidity'])
corr_wind_visibility = df['wind_speed'].corr(df['visibility'])
corr_cloud_rain = df['cloud_cover'].corr(df['rainfall'])

print("Correlation (max_temperature vs max_humidity):", round(corr_temp_humidity, 4))
print("Correlation (wind_speed vs visibility):", round(corr_wind_visibility, 4))
print("Correlation (cloud_cover vs rainfall):", round(corr_cloud_rain, 4))

print("\nFull correlation matrix:")
print(df.select_dtypes(include=[np.number]).corr())

"""The computed correlation coefficients for temperature-vs-humidity and wind-vs-visibility both come out extremely close to zero (on the order of 0.001–0.02), indicating essentially no linear relationship between these variables in this dataset, a result that matters for the broader AI use case since it suggests the data doesn't strongly encode expected physical weather dependencies, so a predictive model built from it may need additional engineered features rather than relying on raw correlations."""

cols_to_normalize = ['max_temperature','min_temperature','wind_speed','rainfall']

for col in cols_to_normalize:
    min_val, max_val = df[col].min(), df[col].max()
    df[col + '_norm'] = (df[col] - min_val) / (max_val - min_val)

print(df[[c for c in df.columns if 'norm' in c]].describe())

"""After min-max scaling, the describe() output on the normalized columns shows all values compressed into the 0-to-1 range while preserving their original relative spread, confirming the transformation worked correctly and that no column (like rainfall, which naturally spans a much larger range than wind speed) will disproportionately dominate a downstream distance-based or gradient-based model."""

# MERGE: attach a city -> state lookup table
city_region = pd.DataFrame({
    'city': ['Delhi','Mumbai','Bangalore','Kolkata','Ahmedabad','Coimbatore','Goa','Jammu','Chennai','Jaipur'],
    'state': ['Delhi','Maharashtra','Karnataka','West Bengal','Gujarat','Tamil Nadu','Goa','Jammu & Kashmir','Tamil Nadu','Rajasthan']
})
df_merged = pd.merge(df, city_region, on='city', how='left')
print("MERGE result:")
print(df_merged[['city','state','max_temperature']].head())

# CONCAT: stack two city subsets back together
delhi_data = df[df['city'] == 'Delhi']
mumbai_data = df[df['city'] == 'Mumbai']
combined = pd.concat([delhi_data, mumbai_data], axis=0, ignore_index=True)
print("\nCONCAT result shape (Delhi + Mumbai):", combined.shape)
print(combined['city'].value_counts())

# JOIN: index-based join of each row with its city average temperature
avg_temp_by_city_df = df.groupby('city')['max_temperature'].mean().rename('avg_city_temp').to_frame()
df_joined = df.set_index('city').join(avg_temp_by_city_df, how='left')
print("\nJOIN result:")
print(df_joined[['max_temperature','avg_city_temp']].head())

"""The merge result successfully attaches a state label to every city record via a shared key, the concatenation result confirms Delhi and Mumbai's subsets combine into one DataFrame with the expected combined row count, and the index-based join places each row's own temperature reading directly next to its city's average temperature. Together these results show how the dataset can be enriched, recombined, and compared against baselines using standard relational operations."""